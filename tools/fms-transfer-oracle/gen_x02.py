#!/usr/bin/env python3
"""Write the import battery x02 and its source files.

    python3 -I gen_x02.py <battery out> <sources dir>

Every probe clears the Contacts table, may add records first, imports one
source file with one import spec, logs Get ( LastError ), the found and
total counts, and dumps the table (Dump: FMPXMLRESULT, UTF-8, creation
order) to omprobe_r_<probe>.xml. The sources are written here, byte for
byte, and copied to the server's Documents folder before the run.
"""
import os
import sys

GS, VT = "\x1d", "\x0b"
COLS = "K | First Name | Last Name | N | D | T | TS | R | VNE"
ROWS = [
    ["1", "Ada", "Lovelace", "1234.5", "12/10/1815", "13:05:09", "01/02/2020 03:04:05 PM", f"r1{GS}{GS}r3", "v"],
    ["2", "Bob", "", "007", "2/29/2024", "1:02", "1/2/2020 15:04", "x", "v"],
    ["3", "Ünï 日本 €", f"a{VT}b", "abc", "13/45/2020", "25:00:00", "garbage", "", "v"],
    ["4", "", "", "", "", "", "", "", "v"],
    ["5", '"quoted"', "tab end ", "-0.001", "1/1/1", "-1:00:00", "12/31/1999 11:59:59.5 PM", f"{GS}{GS}", "v"],
]
DUMP = ("Contacts::K | Contacts::First Name | Contacts::Last Name | Contacts::N | Contacts::D | Contacts::T | "
        "Contacts::TS | Contacts::R | Contacts::NR | Contacts::AE | Contacts::AEO | Contacts::VNE | Contacts::VNO | "
        "Contacts::VU | Contacts::CreatedBy | Contacts::PrimaryKey | Contacts::Title | Addresses::City")


def fmap(names):
    """Map entries for make_patch: bare names are Contacts fields; "=", "!"
    and " +ae" as make_patch's Import Records takes them."""
    out = []
    for n in (x.strip() for x in names.split("|")):
        if n == "-":
            out.append(n)
            continue
        pre = n[0] if n[0] in "=!" else ""
        n = n[len(pre):]
        ae = n.endswith(" +ae")
        n = n[:-4] if ae else n
        out.append(pre + (n if "::" in n else "Contacts::" + n) + (" +ae" if ae else ""))
    return " | ".join(out)


def tab(rows, sep="\r"):
    return sep.join("\t".join(r) for r in rows) + sep


def main():
    out, src = sys.argv[1], sys.argv[2]
    os.makedirs(src, exist_ok=True)
    files = {}

    def put(name, data):
        files[name] = data.encode("utf-8") if isinstance(data, str) else data

    put("omprobe_s_basic.tab", tab(ROWS))
    put("omprobe_s_lf.tab", tab(ROWS, "\n"))
    put("omprobe_s_crlf.tab", tab(ROWS, "\r\n"))
    put("omprobe_s_blank.tab", "\r".join("\t".join(r) for r in ROWS[:2]) + "\r\r" + tab(ROWS[2:4]).rstrip("\r"))
    put("omprobe_s_bom8.tab", b"\xef\xbb\xbf" + tab(ROWS).encode())
    put("omprobe_s_u16le.tab", b"\xff\xfe" + tab(ROWS).encode("utf-16-le"))
    put("omprobe_s_u16be.tab", b"\xfe\xff" + tab(ROWS).encode("utf-16-be"))
    put("omprobe_s_u16nobom.tab", tab(ROWS).encode("utf-16-le"))
    latin = [["1", "café – €5", "naïve", "1", "", "", "", "", "v"]]
    put("omprobe_s_ansi.tab", tab(latin).encode("cp1252"))
    put("omprobe_s_mac.tab", tab([["1", "café – 5", "naïve", "1", "", "", "", "", "v"]]).encode("mac_roman"))
    put("omprobe_s_dos.tab", tab([["1", "café", "naïve", "1", "", "", "", "", "v"]]).encode("cp437"))
    put("omprobe_s_sjis.tab", tab([["1", "日本語", "ﾃｽﾄ", "1", "", "", "", "", "v"]]).encode("shift_jis"))
    csv = ('"1","a,b","He said ""hi""","1.5",,,,,"v"\r'
           '2,plain, spaced ,007,,,,,v\r'
           '"3","multi\rline","cr\nlf","",,,,,"v"\r'
           '"4","crlf\r\ninside","  ""x"" ",1,,,,,"v"\r'
           '"5","short"\r'
           '"6","long","b","2","","","","","v","extra","more"\r'
           ' "7" ,"q"x"y","",,,,,,v\r')
    put("omprobe_s_csv.csv", csv)
    put("omprobe_s_csvlf.csv", csv.replace("\r", "\n"))
    hdr = ["K", "First Name", "Last Name", "N", "D", "T", "TS", "R", "VNE"]
    put("omprobe_s_names.tab", tab([hdr] + ROWS[:3]))
    put("omprobe_s_names_shuffled.tab", tab([["First Name", "K", "VNE", "Nonexistent"], ["Ada", "1", "v", "z"],
                                             ["Bob", "2", "v", "z"]]))
    put("omprobe_s_names2.tab", tab([ROWS[0], hdr] + ROWS[1:3]))
    valid = [["1", "x", "u1", "o"], ["2", "", "u2", "o"], ["3", "y", "u1", "o"], ["4", "z", "u4", ""], ["5", "w", "u5", "o"]]
    put("omprobe_s_valid.tab", tab(valid))
    put("omprobe_s_ae.tab", tab([["1", "sAE", "sAEO", "v"], ["2", "", "", "v"]]))
    put("omprobe_s_rep.tab", tab([["1", f"a{GS}b{GS}c", f"1{GS}2", "v"], ["2", "solo", "", "v"], ["3", f"{GS}x{GS}{GS}y", "", "v"]]))
    put("omprobe_s_vt.tab", tab([["1", f"one{VT}two", "v"], ["2", '"a\tb"', "v"], ["3", '"q"', "v"]]))
    put("omprobe_s_empty.tab", b"")
    put("omprobe_s_addr.tab", tab([["C1", "Paris"], ["C1", "Rome"], ["C9", "Nowhere"]]))
    put("omprobe_s_more.tab", tab(ROWS + [["6", "Fay", "", "", "", "", "", "", "v"], ["7", "Gus", "", "", "", "", "", "", "v"]]))

    L = []
    w = L.append
    w("# Import Records probes (battery x02), generated by gen_x02.py: every probe")
    w("# clears Contacts, imports one source (sources/x02) and dumps the table.")
    w("")
    w("== Clear")
    w('Go to Layout [ "Contact List" ]')
    w("Show All Records")
    w("Loop")
    w("Exit Loop If [ Get ( FoundCount ) = 0 ]")
    w("Delete Record/Request [ With dialog: Off ]")
    w("End Loop")
    w("")
    w("== Dump")
    w('Go to Layout [ "Contact List" ]')
    w("Show All Records")
    w("Step 21")
    w('Set Variable [ $p0 ; Get ( DocumentsPath ) & "omprobe_r_" & Get ( ScriptParameter ) & ".xml" ]')
    w(f'Export Records [ "file:$p0" ; Type: XMLE ; Charset: 4 ; Fields: {DUMP} ; With dialog: Off ]')
    w("")
    w("== Make")
    w("# parameter: K values separated by returns; each record gets First Name old<K>")
    w("Set Variable [ $i ; 1 ]")
    w("Loop")
    w("Exit Loop If [ $i > ValueCount ( Get ( ScriptParameter ) ) ]")
    w("New Record/Request")
    w("Set Field [ Contacts::K ; GetValue ( Get ( ScriptParameter ) ; $i ) ]")
    w('Set Field [ Contacts::First Name ; "old" & GetValue ( Get ( ScriptParameter ) ; $i ) ]')
    w('Set Field [ Contacts::VNE ; "pre" ]')
    w('Set Field [ Contacts::VNO ; "pre" ]')
    w('Set Field [ Contacts::PrimaryKey ; "C" & GetValue ( Get ( ScriptParameter ) ; $i ) ]')
    w("Set Variable [ $i ; $i + 1 ]")
    w("End Loop")
    w("Commit Records/Requests [ With dialog: Off ]")
    w("")
    probes = []

    XMAP = fmap("K | First Name | Last Name | - | Title | - | - | N | D | T | TS | R | NR | - | - | VNE")

    def probe(name, source, spec, pre=None, steps=None, literal=False):
        probes.append(name)
        w(f"== {name}")
        w("Set Error Capture [ On ]")
        w('Perform Script [ "Clear" ]')
        if pre:
            w(f'Perform Script [ "Make" ; Parameter: "{pre}" ]')
            w('Go to Layout [ "Contact List" ]')
            w("Show All Records")
        for s in steps or []:
            w(s)
        if literal:
            # an XML source path is stored in the profile and not expanded
            w(f'Import Records [ "filelinux:/opt/FileMaker/FileMaker Server/Data/Documents/{source}" ; {spec} ; With dialog: Off ]')
        else:
            w(f'Set Variable [ $p0 ; Get ( DocumentsPath ) & "{source}" ]')
            w(f'Import Records [ "file:$p0" ; {spec} ; With dialog: Off ]')
        w(f'Set Variable [ $$log ; $$log & "{name}" & Char ( 9 ) & Get ( LastError ) & Char ( 9 ) & Get ( FoundCount ) & '
          'Char ( 9 ) & Get ( TotalRecordCount ) & ¶ ]')
        w(f'Perform Script [ "Dump" ; Parameter: "{name}" ]')
        w("")

    M = fmap(COLS)
    base = f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {M}"
    probe("i_add", "omprobe_s_basic.tab", base)
    probe("i_lf", "omprobe_s_lf.tab", base)
    probe("i_crlf", "omprobe_s_crlf.tab", base)
    probe("i_blank", "omprobe_s_blank.tab", base)
    probe("i_bom8", "omprobe_s_bom8.tab", base)
    probe("i_bom8_ansi", "omprobe_s_bom8.tab", base.replace("Charset: 5", "Charset: 0"))
    probe("i_u8_as_ansi", "omprobe_s_basic.tab", base.replace("Charset: 5", "Charset: 0"))
    probe("i_u16le", "omprobe_s_u16le.tab", base.replace("Charset: 5", "Charset: 3"))
    probe("i_u16be", "omprobe_s_u16be.tab", base.replace("Charset: 5", "Charset: 4"))
    probe("i_u16le_as_be", "omprobe_s_u16le.tab", base.replace("Charset: 5", "Charset: 4"))
    probe("i_u16nobom", "omprobe_s_u16nobom.tab", base.replace("Charset: 5", "Charset: 3"))
    probe("i_ansi", "omprobe_s_ansi.tab", base.replace("Charset: 5", "Charset: 0"))
    probe("i_mac", "omprobe_s_mac.tab", base.replace("Charset: 5", "Charset: 2"))
    probe("i_dos", "omprobe_s_dos.tab", base.replace("Charset: 5", "Charset: 1"))
    probe("i_sjis", "omprobe_s_sjis.tab", base.replace("Charset: 5", "Charset: 6"))
    probe("i_csv", "omprobe_s_csv.csv", base.replace("TABS", "COMS"))
    probe("i_csvlf", "omprobe_s_csvlf.csv", base.replace("TABS", "COMS"))
    probe("i_tab_csv", "omprobe_s_csv.csv", base)
    probe("i_names", "omprobe_s_names.tab", base + " ; Names: 1")
    probe("i_names_match", "omprobe_s_names_shuffled.tab",
          f"Type: TABS ; Target: Contacts ; Charset: 5 ; Names: 1 ; Match names: On ; Map: {fmap('K | First Name | VNE')}")
    probe("i_names_nomatch", "omprobe_s_names_shuffled.tab",
          f"Type: TABS ; Target: Contacts ; Charset: 5 ; Names: 1 ; Map: {fmap('K | First Name | VNE')}")
    probe("i_names2", "omprobe_s_names2.tab", base + " ; Names: 2")
    upd = f"Type: TABS ; Target: Contacts ; Charset: 5 ; Action: Update ; Map: {fmap('=K | First Name | Last Name | N | D | T | TS | R | VNE')}"
    probe("i_upd", "omprobe_s_basic.tab", upd, pre="1¶2¶9")
    probe("i_upd_add", "omprobe_s_basic.tab", upd + " ; Add remaining: On", pre="1¶2¶9")
    probe("i_upd_dup", "omprobe_s_basic.tab", upd, pre="1¶1¶2")
    probe("i_upd_found", "omprobe_s_basic.tab", upd, pre="1¶2¶3", steps=["Go to Record/Request/Page [ First ]", "Omit Record"])
    rep = f"Type: TABS ; Target: Contacts ; Charset: 5 ; Action: Replace ; Map: {M}"
    probe("i_replace", "omprobe_s_basic.tab", rep, pre="a¶b¶c")
    probe("i_replace_add", "omprobe_s_basic.tab", rep + " ; Add remaining: On", pre="a¶b¶c")
    probe("i_replace_more", "omprobe_s_basic.tab", rep, pre="a¶b¶c¶d¶e¶f¶g")
    ae = fmap("K | AE | AEO | VNE")
    probe("i_ae_on", "omprobe_s_ae.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Auto-enter: On ; Map: {ae}")
    probe("i_ae_off", "omprobe_s_ae.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {ae}")
    probe("i_ae_field", "omprobe_s_ae.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Auto-enter: On ; Map: {fmap('K | AE +ae | AEO | VNE')}")
    probe("i_ae_upd", "omprobe_s_ae.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Auto-enter: On ; Action: Update ; Map: {fmap('=K | AE | AEO | VNE')}", pre="1¶2")
    probe("i_valid", "omprobe_s_valid.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | VNE | VU | VNO')}")
    probe("i_split", "omprobe_s_rep.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Split repetitions: On ; Map: {fmap('K | R | NR | VNE')}")
    probe("i_rep", "omprobe_s_rep.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | R | NR | VNE')}")
    probe("i_rep_single", "omprobe_s_rep.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | First Name | Title | VNE')}")
    probe("i_vt", "omprobe_s_vt.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | First Name | VNE')}")
    probe("i_fewer_map", "omprobe_s_basic.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | First Name')}")
    probe("i_skip_cols", "omprobe_s_basic.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | - | First Name | !Last Name | - | - | - | - | VNE')}")
    probe("i_calc", "omprobe_s_basic.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {fmap('K | CN | G | - | - | - | - | - | VNE')}")
    probe("i_missing", "omprobe_s_nothere.tab", base)
    probe("i_empty", "omprobe_s_empty.tab", base)
    probe("i_more", "omprobe_s_more.tab", base)
    # x01's own exports (the G column, "glob" everywhere, fills VNE)
    probe("i_xml", "omprobe_s_x.xml", f"Type: XML ; Target: Contacts ; Charset: 5 ; Map: {XMAP}", literal=True)
    probe("i_mrge", "omprobe_s_m.mer", f"Type: MRGE ; Target: Contacts ; Charset: 5 ; Map: {XMAP}")
    probe("i_mrge_names", "omprobe_s_m.mer", f"Type: MRGE ; Target: Contacts ; Charset: 5 ; Names: 1 ; Map: {XMAP}")
    probe("i_tab_x", "omprobe_s_t.tab", f"Type: TABS ; Target: Contacts ; Charset: 5 ; Map: {XMAP}")
    probe("i_csv_x", "omprobe_s_c.csv", f"Type: COMS ; Target: Contacts ; Charset: 5 ; Map: {XMAP}")
    probe("i_names_first", "omprobe_s_names.tab", base + " ; Names: 1 ; Match names: On")
    probe("i_addr", "omprobe_s_addr.tab", "Type: TABS ; Target: Addresses ; Charset: 5 ; Map: Addresses::ForeignKey | Addresses::City", pre="1")

    w("== Run")
    w('Set Variable [ $$log ; "" ]')
    for p in probes:
        w(f'Perform Script [ "{p}" ]')
    w('Perform Script [ "Clear" ]')
    w("New Record/Request")
    w('Set Field [ Contacts::VNE ; "log" ]')
    w('Set Field [ Contacts::VNO ; "log" ]')
    w('Set Field [ Contacts::VU ; "log" ]')
    w("Set Field [ Contacts::LOG ; $$log ]")
    w("Commit Records/Requests [ With dialog: Off ]")
    w('Set Variable [ $p0 ; Get ( DocumentsPath ) & "omprobe_log.tab" ]')
    w('Export Records [ "file:$p0" ; Type: TABS ; Charset: 4 ; Fields: Contacts::LOG ; With dialog: Off ]')
    w("")
    w("--- run")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    for name, data in files.items():
        open(os.path.join(src, name), "wb").write(data)


if __name__ == "__main__":
    main()
